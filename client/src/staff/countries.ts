const byAlpha3 = new Map(COUNTRIES.map(country => [country.a3, country]));

export function countryByAlpha3(alpha3: string | null | undefined) {
  return alpha3 ? byAlpha3.get(alpha3.toUpperCase()) : undefined;
}

const displayNameCaches = new Map<string, Intl.DisplayNames>();

/** Localized country name for an ISO alpha-3 code, falling back to the code. */
export function nationalityName(
  alpha3: string | null | undefined,
  locale: string
): string | null {
  const country = countryByAlpha3(alpha3);
  if (!country) return alpha3 ?? null;
  let names = displayNameCaches.get(locale);
  if (!names) {
    try {
      names = new Intl.DisplayNames([locale], { type: "region" });
      displayNameCaches.set(locale, names);
    } catch {
      return country.en;
    }
  }
  return names.of(country.a2) ?? country.en;
}
